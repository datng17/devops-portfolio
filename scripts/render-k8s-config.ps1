#Requires -Version 7
<#
.SYNOPSIS
  Renders k8s/app/ingress-config.env from terraform/infra outputs.

.DESCRIPTION
  The file is gitignored (k8s/**/*.env) because it holds account-specific
  values. kustomize reads it through a local-config ConfigMap and replaces
  the Ingress certificate ARN, the Ingress security group and the image
  repository. k8s/platform/log-sink-config.env is generated by
  terraform/platform instead.

.EXAMPLE
  pwsh scripts/render-k8s-config.ps1
  kubectl apply -k k8s/app
#>
[CmdletBinding()]
param(
    [string]$InfraDir = (Join-Path $PSScriptRoot '..' 'terraform' 'infra'),
    [string]$OutFile  = (Join-Path $PSScriptRoot '..' 'k8s' 'app' 'ingress-config.env')
)

$ErrorActionPreference = 'Stop'

$json = terraform "-chdir=$InfraDir" output -json
if ($LASTEXITCODE -ne 0) { throw "terraform output failed (exit $LASTEXITCODE). Run 'terraform init' in $InfraDir first." }
$outputs = $json | ConvertFrom-Json

function Get-Output([string]$Name) {
    $prop = $outputs.PSObject.Properties[$Name]
    if (-not $prop -or [string]::IsNullOrWhiteSpace([string]$prop.Value.value)) {
        throw "Terraform output '$Name' is missing or empty."
    }
    return [string]$prop.Value.value
}

$values = [ordered]@{
    ACM_CERTIFICATE_ARN   = Get-Output 'acm_certificate_arn'
    ALB_SECURITY_GROUP_ID = Get-Output 'alb_security_group_id'
    ECR_REPOSITORY_URL    = Get-Output 'ecr_repository_url'
}

$status = $outputs.PSObject.Properties['acm_certificate_status']
if ($status -and $status.Value.value -ne 'ISSUED') {
    Write-Warning "ACM certificate status is '$($status.Value.value)', not ISSUED. The ALB HTTPS listener will fail until it is."
}

$lines = $values.GetEnumerator() | ForEach-Object { "$($_.Key)=$($_.Value)" }
# LF line endings and no BOM, same as the platform env file.
[System.IO.File]::WriteAllText(
    [System.IO.Path]::GetFullPath($OutFile),
    (($lines -join "`n") + "`n"),
    [System.Text.UTF8Encoding]::new($false)
)
Write-Host "Wrote $([System.IO.Path]::GetFullPath($OutFile)):"
$values.Keys | ForEach-Object { Write-Host "  $_" }
